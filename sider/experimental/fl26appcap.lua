--[[
fl26appcap -- the PlayerAppearance table from 30,024 to 65000 records.

Generated by tools/appcap.py; do not edit the patch list by hand.

What it fixes. The game keeps every player's appearance (the record PlayerAppearance.bin
holds for him: skin, build, hair ...) in a table of 30,024 records. A database with more
appearance records than that loses the rest: with fl26regen the load stops at 30,023 (it
used to run past the table and crash Edit, GitHub #65), and the players whose records were
left out draw the default look in game.

What this writes. The table is the last array of its object ([[exe+0x3705e10] + 0x60]), so
it grows in place: the object grows from 0x260554 to 0x4c7254 bytes, the two u16 counts
behind the table move from +0x260550/+0x260552 to +0x4c7250/+0x4c7252, and the cap
(0x7548) and cap - 1 move with them. The table stays at +0x50910, so no access to a record
changes. Every patch rewrites one 32-bit field of one instruction, same length:

  * the allocation size at both `new`s, the three sized deletes and the backup's memset;
  * the chunk count of the two unrolled copies between the object and its backup
    ([owner+0x88]); the new size keeps their fixed 0x54-byte tail;
  * the constructor's memset of the table;
  * every access to the two counts (21) and every cap / cap - 1 immediate (7).

tools/appcap.py found these by decoding the whole code section and by searching every
section of the exe for the old displacements; it refuses to emit the module if a single
reference is left over.

The count stays a u16, so 65000 is near the ceiling: a PlayerAppearance.bin of up to
64999 records loads whole (the loader keeps one record free, as before).

ORDER: load this BEFORE fl26regen.lua (right after fl26caps.lua). fl26regen reads the cap
from the code when it starts; loaded after it, this module finds fl26regen's hook where it
expects the original bytes, refuses, and the game keeps the old 30,024.

Saves: the table is built from PlayerAppearance.bin at every start. No fixed-size copy of it
exists anywhere else in the exe (the scans above), and Edit's own changes go through the
game's insert/lookup functions, which are bounded by the count -- but Edit-data saving with
more than 30,024 records has not been run in a game yet.

Same apply rule as every fl26 module: verify all sites first, write only if all match.
--]]

