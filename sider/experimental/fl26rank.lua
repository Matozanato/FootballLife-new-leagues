local function bin2hex(s)
  return (s:gsub(".", function(c) return string.format("%02x", c:byte()) end))
end

local function hex2bin(h)
  return (h:gsub("%x%x", function(b) return string.char(tonumber(b, 16)) end))
end

function m.init(ctx)
  -- 1. verify every site before touching any of them
  for i, p in ipairs(PATCHES) do
    local got = bin2hex(memory.read(p.va, #p.old / 2))
    if got ~= p.old then
      log(string.format("fl26rank: bytes at 0x%x are %s, expected %s (%s) -- aborting, nothing written",
                        p.va, got, p.old, p.why))
      return
    end
  end

  -- 2. write
  local counts = {}
  for _, p in ipairs(PATCHES) do
    memory.write(p.va, hex2bin(p.new))
    local role = p.why:match("^[^:]+")
    counts[role] = (counts[role] or 0) + 1
  end

  -- 3. read back, so a silently failed write cannot pass for a good one
  local bad = 0
  for _, p in ipairs(PATCHES) do
    if bin2hex(memory.read(p.va, #p.new / 2)) ~= p.new then bad = bad + 1 end
  end
  if bad > 0 then
    log(string.format("fl26rank: %d of %d sites did not take the new bytes", bad, #PATCHES))
    return
  end

  local parts = {}
  for role, n in pairs(counts) do parts[#parts + 1] = string.format("%s %d", role, n) end
  table.sort(parts)
  log(string.format("fl26rank: live -- league rank widened to bits 29-31 (%d sites: %s); " ..
                    "ranks 1-7 now, group count keeps 5 bits", #PATCHES, table.concat(parts, ", ")))
end

return m
