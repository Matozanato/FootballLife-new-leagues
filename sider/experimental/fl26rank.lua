--[[
fl26rank -- give the league rank one more bit, so a national pyramid can be more than three
deep.

Why: every regulation record carries a rank -- first division, second, third -- and the game
keeps it in the TOP TWO BITS of the flags word at +0x304. Two bits count to three. We have
added fourth and fifth divisions, so our D3, D4 and D5 all end up carrying the value 3, and
the UI that pairs a league with the one above and below it then cannot tell them apart: Ligue
2 shows no lower league at all (that panel only computes one for rank 1), and France D4 shows
itself as its own lower league.

What this does: moves the rank down one bit, to bits 29-31, so it counts to seven. Bit 29 is
today the top bit of the group count (bits 24-29), and the loader masks that count to five
bits before storing it (0x1414f828d: movzx edx, byte [rax+0x10]; and dl,0x1f), so nothing
shipped ever sets bit 29. The group count keeps bits 24-28, which is still up to 31 groups --
more than the data file can even express.

Every instruction involved re-encodes to the same length, so this is an in-place byte patch:
no trampolines, no extra memory, nothing relocated.

  rank read    shr/sar r, 0x1e            -> 0x1d
               and/test r, 0xc0000000     -> 0xe0000000
               cmp r, 0x40000000 / 0x80000000 / 0xc0000000 -> 0x20000000 / 0x40000000 / 0x60000000
               and r, 0x3fffffff          -> 0x1fffffff   (record copier: "everything but the rank")
  rank write   0x1414c9cc0 mask, 0x1414c9ccd shl
  group read   and r, 0x3f -> 0x1f after shr r,0x18;  and r, 0x3f000000 -> 0x1f000000
  group write  0x1414c9e70 mask, 0x1414c9e7d and

The sites were found by walking every reference to +0x304 in .trace, decoding the instruction
whose displacement lands exactly there, and following the register the value went into -- an
idiom counts only when it acts on that register, because a compare against 0x40000000 near a
read proves nothing on its own.

The word is also reached through its top byte. +0x307 is bits 24-31 of the same word, so in
that byte the group count is the low six bits and the rank is the top two; ten places read it
that way (test byte [reg+0x307], 0x3f, or movzx then and r,0x3f). Those masks take six bits,
so once a league carries rank 4 or higher -- which sets bit 29 -- an unnarrowed read there
returns 32 plus the real group count, and that number is used as a loop bound. The same walk
is therefore run a second time over the displacement 0x307, with the byte-sized forms of the
same idioms (shr r,6 for the rank, and/test 0x3f -> 0x1f for the count).

Three sites around 0x1422b9xxx that match the idiom by eye were excluded by hand: their
structure has a +0xb98 field, so it is not a regulation record.
Generated by tools/mkrankpatch.py; do not edit the table by hand.

All-or-nothing: every old byte sequence is verified first, and if a single one differs nothing
at all is written and the game runs unmodified.

After this, a league's rank comes from the data file exactly as before -- Regulation row +0x10
bits 15-17 -- except that the value may now be 4 or 5 as well. The loader already passes three
bits (0x1414f82a8: shr edx,0xf; and dl,7); only the setter was throwing the third one away.
--]]

